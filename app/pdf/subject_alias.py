# 反向索引：PDF 原文科目名 → (标准科目名, 报表类型)
# 三个报表的 alias 几乎不重名（如"净利润"只在利润表，"营业利润"只在利润表，
# "经营活动产生的现金流量净额"只在现金流量表），所以单一全局索引即可
_ALIAS_TO_STANDARD: dict[str, tuple[str, str]] = {}  # alias -> (standard, statement_type)
for _stmt, _subjects in SUBJECT_ALIASES_BY_STATEMENT.items():
    for _std, _aliases in _subjects.items():
        for _alias in _aliases:
            # 不覆盖已有映射（保持首次出现的优先级）
            if _alias not in _ALIAS_TO_STANDARD:
                _ALIAS_TO_STANDARD[_alias] = (_std, _stmt)


